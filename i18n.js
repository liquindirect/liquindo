class LanguageManager {
  constructor() {
    this.currentLanguage =
      this.getStoredLanguage() || "en";

    if (!translations[this.currentLanguage]) {
      this.currentLanguage = "en";
    }

    this.init();
  }

  getStoredLanguage() {
    try {
      return localStorage.getItem(
        "liquindo-language"
      );
    } catch {
      return null;
    }
  }

  setLanguage(lang) {
    if (!translations[lang]) {
      return;
    }

    this.currentLanguage = lang;

    try {
      localStorage.setItem(
        "liquindo-language",
        lang
      );
    } catch {
      // The site still works if localStorage is unavailable.
    }

    this.updatePageLanguage();
  }

  get(key) {
    return (
      translations[this.currentLanguage]?.[key] ??
      translations.en[key] ??
      key
    );
  }

  updatePageLanguage() {
    document
      .querySelectorAll("[data-i18n]")
      .forEach((element) => {
        const key =
          element.getAttribute("data-i18n");

        element.textContent = this.get(key);
      });

    const languageSwitcher =
      document.getElementById(
        "language-switcher"
      );

    if (languageSwitcher) {
      languageSwitcher.value =
        this.currentLanguage;
    }

    document.documentElement.lang =
      this.currentLanguage;

    document.dispatchEvent(
      new CustomEvent(
        "liquindo-language-changed",
        {
          detail: {
            language: this.currentLanguage
          }
        }
      )
    );
  }

  init() {
    this.updatePageLanguage();

    const languageSwitcher =
      document.getElementById(
        "language-switcher"
      );

    if (languageSwitcher) {
      languageSwitcher.addEventListener(
        "change",
        (event) => {
          this.setLanguage(
            event.target.value
          );
        }
      );
    }
  }
}

document.addEventListener(
  "DOMContentLoaded",
  () => {
    window.languageManager =
      new LanguageManager();
  }
);
